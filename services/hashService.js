// Импортируем библиотеку bcrypt для безопасного хэширования паролей
import bcrypt from "bcrypt";

// Объявляем класс HashService, который будет группировать методы для работы с паролями
class HashService {
  
  // Асинхронный метод для генерации хэша из обычной строки пароля
  async hashPassword(password) {
    // Блок try-catch для перехвата и обработки возможных ошибок
    try {
      // Генерируем "соль" (случайные данные) с фактором стоимости 10 для усложнения подбора
      const salt = await bcrypt.genSalt(10)
      
      // Хэшируем пароль, используя сгенерированную соль
      const hash = await bcrypt.hash(password, salt)
      
      // Возвращаем готовый хэш пароля
      return hash;
      
    // Если на каком-то этапе произошла ошибка (например, сбой bcrypt)
    } catch(err) {
      // Выбрасываем новое исключение с понятным описанием ошибки
      throw new Error("Ошибка при хэшировании пароля")
    }
  }

  // Асинхронный метод для проверки соответствия чистого пароля и существующего хэша
  async comparePassword(password, hash) {
    // Блок try-catch для безопасного выполнения сравнения
    try {
      // Сравниваем пароль и хэш с помощью встроенного метода bcrypt и возвращаем результат (true/false)
      return await bcrypt.compare(password, hash)
      
    // Если в процессе сравнения возникла ошибка
    } catch(err) {
      // Выбрасываем новое исключение с сообщением об ошибке
      throw new Error("Ошибка при сравнении паролей");
    }
  }
}

// Экспортируем уже созданный экземпляр класса (паттерн Синглтон) для использования в других модулях
export default new HashService();
